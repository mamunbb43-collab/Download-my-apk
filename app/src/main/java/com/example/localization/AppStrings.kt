object Formatters {
    private val bnDigits = charArrayOf('০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯')

    fun toLocalizedDigits(input: String, isBengali: Boolean): String {
        if (!isBengali) return input
        val sb = StringBuilder(input.length)
        for (c in input) {
            if (c in '0'..'9') {
                sb.append(bnDigits[c - '0'])
            } else {
                sb.append(c)
            }
        }
        return sb.toString()
    }

    fun formatMoney(
        amount: Double,
        currency: AppCurrency,
        isBengali: Boolean,
        includeDecimals: Boolean = false
    ): String {
        val nf = NumberFormat.getNumberInstance(Locale.US).apply {
            minimumFractionDigits = if (includeDecimals || (amount % 1.0 != 0.0)) 2 else 0
            maximumFractionDigits = 2
        }
        val sign = if (amount < 0) "-" else ""
        val formatted = nf.format(kotlin.math.abs(amount))
        val raw = "$sign${currency.symbol}$formatted"
        return toLocalizedDigits(raw, isBengali)
    }

    fun formatCount(count: Int, isBengali: Boolean, unitSuffixBn: String = "টি", unitSuffixEn: String = ""): String {
        val num = toLocalizedDigits(count.toString(), isBengali)
        val suffix = if (isBengali) unitSuffixBn else unitSuffixEn
        return if (suffix.isNotEmpty()) "$num $suffix" else num
    }

    fun formatQty(qty: Double, isBengali: Boolean): String {
        val text = if (qty % 1.0 == 0.0) qty.toLong().toString() else String.format(Locale.US, "%.2f", qty)
        return toLocalizedDigits(text, isBengali)
    }

    fun formatDate(timestamp: Long, pattern: String, isBengali: Boolean): String {
        val locale = if (isBengali && pattern == DateFormatOption.READABLE.pattern) {
            Locale("bn", "BD")
        } else {
            Locale.ENGLISH
        }
        val sdf = SimpleDateFormat(pattern, locale)
        val raw = sdf.format(Date(timestamp))
        return toLocalizedDigits(raw, isBengali)
    }

    fun formatDateTime(timestamp: Long, isBengali: Boolean): String {
        val locale = if (isBengali) Locale("bn", "BD") else Locale.ENGLISH
        val sdf = SimpleDateFormat("dd MMM, yyyy hh:mm a", locale)
        return toLocalizedDigits(sdf.format(Date(timestamp)), isBengali)
    }
}
